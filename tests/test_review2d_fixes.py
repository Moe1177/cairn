def _edges(ws: Path, kind: EdgeType) -> dict[tuple[str, str], Confidence]:
    return {
        (e.source, e.target): e.confidence
        for e in scan_workspace(ws).workspace.edges
        if e.type is kind
    }


# --- C1: a deeply nested compose (or pnpm) file can't crash the process -------------------


def test_deeply_nested_yaml_never_crashes_a_scan(tmp_path: Path) -> None:
    nested = "services: " + "[" * 3000 + "]" * 3000 + "\n"
    write(tmp_path, "evil.py", "")  # keep a module-free script below
    make_repo(
        tmp_path / "ws",
        "infra",
        {"docker-compose.yml": nested, "pnpm-workspace.yaml": "packages: " + "[" * 3000},
    )
    script = (
        "import sys; from pathlib import Path; from cairn.scan import scan_workspace;"
        f"r = scan_workspace(Path(r'{tmp_path / 'ws'}')); print('ok', len(r.workspace.repos))"
    )
    done = subprocess.run(
        [sys.executable, "-c", script], capture_output=True, text=True, timeout=120
    )
    assert done.returncode == 0 and "ok 1" in done.stdout, done.stderr[-500:]


# --- C2: two monorepos with the same internal package names never link -------------------


def test_internal_workspace_packages_never_link_unrelated_monorepos(tmp_path: Path) -> None:
    for repo in ("shop-mono", "blog-mono"):
        root = make_repo(
            tmp_path, repo, {"package.json": json.dumps({"name": repo, "private": True})}
        )
        write(root, "pnpm-workspace.yaml", "packages:\n  - packages/*\n  - apps/*\n")
        write(root, "packages/ui/package.json", json.dumps({"name": "@repo/ui"}))
        write(
            root,
            "apps/web/package.json",
            json.dumps({"name": "web", "dependencies": {"@repo/ui": "workspace:*"}}),
        )
    assert _edges(tmp_path, EdgeType.DEPENDS_ON_PACKAGE) == {}


# --- I1, I2: compose anchors and workspace globs stay bounded ------------------------------


def test_compose_anchor_bombs_are_bounded(tmp_path: Path) -> None:
    deps = "".join(f"      - s{i}\n" for i in range(3000))
    services = "".join(f"  s{i}: *base\n" for i in range(3000))
    text = f"x-base: &base\n  build: ../app\n  depends_on:\n{deps}services:\n{services}"
    repo = make_repo(tmp_path, "infra", {"docker-compose.yml": text[:250_000]})
    start = time.perf_counter()
    InfraDetector().run(ctx_for(tmp_path, repo))
    assert time.perf_counter() - start < time_limit(1.5)


