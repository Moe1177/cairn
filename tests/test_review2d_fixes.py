# --- I3 + M2: generated gRPC code and generic service names -------------------------------


def test_generated_grpc_code_and_generic_services_make_no_false_links(tmp_path: Path) -> None:
    generated = "// Code generated by protoc-gen-go-grpc. DO NOT EDIT.\nfunc RegisterTripsServiceServer(s, srv) {}\nfunc NewTripsServiceClient(cc) {}\n"
    make_repo(
        tmp_path,
        "trips-svc",
        {"pb/trips_grpc.pb.go": generated, "main.go": "pb.RegisterTripsServiceServer(s, &srv{})"},
    )
    make_repo(
        tmp_path,
        "gateway",
        {"pb/trips_grpc.pb.go": generated, "client.go": "c := pb.NewTripsServiceClient(conn)"},
    )
    make_repo(
        tmp_path,
        "protos",
        {
            "gen/trips_pb2_grpc.py": "class TripsServiceStub(object):\n    pass\ndef add_TripsServiceServicer_to_server(s, srv):\n    pass\n"
        },
    )
    make_repo(
        tmp_path,
        "chain",
        {"app.go": "types.RegisterQueryServer(s, k)\nhealth.RegisterHealthServer(s, h)"},
    )
    make_repo(
        tmp_path, "web", {"q.ts": "const qc = new QueryClient()\nconst h = new HealthClient(addr)"}
    )
    assert _edges(tmp_path, EdgeType.GRPC) == {("gateway", "trips-svc"): Confidence.INFERRED}


# --- I4 + M1: hints must name exactly the target ------------------------------------------


def test_company_prefix_in_hint_doesnt_promote_and_named_absent_owner_is_not_inferred(
    tmp_path: Path,
) -> None:
    make_repo(
        tmp_path,
        "acme-trips",
        {"package.json": json.dumps({"name": "@acme/trips"}), "s.js": "app.get('/invoices', h)"},
    )
