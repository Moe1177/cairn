# --- I7, I8, M6: monorepo surfaces ----------------------------------------------------------


def _big_monorepo(ws: Path) -> None:
    root = make_repo(
        ws,
        "platform",
        {"package.json": json.dumps({"name": "platform", "scripts": {"dev": "turbo dev"}})},
    )
    write(root, "pnpm-workspace.yaml", "packages:\n  - packages/*\n")
    for i in range(60):
        write(root, f"packages/p{i:02d}/package.json", json.dumps({"name": f"@acme/p{i:02d}"}))
    make_repo(ws, "billing")
    sub = make_repo(ws, "tools-mono", {"go.work": "use ./svc/billing\n"})
    write(sub, "svc/billing/go.mod", "module github.com/acme/billing\n")


def test_packages_are_capped_on_cards_and_runs_survive(tmp_path: Path) -> None:
    _big_monorepo(tmp_path)
    write_outputs(tmp_path, scan_workspace(tmp_path))
    card = (cards_dir(tmp_path) / "platform.md").read_text(encoding="utf-8")
    packages = card.split("## Packages", 1)[1].split("##", 1)[0]
    assert len([line for line in packages.splitlines() if "→" in line]) <= 8
    assert "## Run" in card and "npm run dev" in card


def test_repo_ids_win_over_package_names_and_duplicates_are_listed(tmp_path: Path) -> None:
    _big_monorepo(tmp_path)
    write_outputs(tmp_path, scan_workspace(tmp_path))
    assert tools.resolve_text(tmp_path, "billing").splitlines()[0].startswith("- billing")


def test_package_paths_follow_a_moved_monorepo(tmp_path: Path) -> None:
    # A real git repo, so the per-repo cache is used across the move.
    from cairn.bench.workspace import materialize

    src = tmp_path / "src" / "platform"
    write(src, ".fixture-repo", "")
    write(src, "package.json", "{}")
    write(src, "pnpm-workspace.yaml", "packages:\n  - packages/*\n")
    write(src, "packages/ui/package.json", json.dumps({"name": "@acme/ui"}))
    ws = materialize(tmp_path / "src", tmp_path / "ws")
    scan_workspace(ws)  # fills the cache
    (ws / "services").mkdir()
    (ws / "platform").rename(ws / "services" / "platform")
    repo = scan_workspace(ws).workspace.repo("platform")
    assert repo is not None and repo.packages[0].path == "services/platform/packages/ui"


