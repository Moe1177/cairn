# --- M4, M5: compose images and remote build contexts ----------------------------------------


def test_public_images_and_git_contexts_make_no_compose_links(tmp_path: Path) -> None:
    compose = (
        "services:\n  api:\n    build: ../api\n    depends_on: [db, ext]\n"
        "  db:\n    image: postgres:16\n  ext:\n    build: https://github.com/acme/public-api.git#main\n"
    )
    make_repo(tmp_path, "infra", {"docker-compose.yml": compose})
    make_repo(tmp_path, "api")
    make_repo(tmp_path, "postgres")
    make_repo(tmp_path, "public-api")
    assert _edges(tmp_path, EdgeType.COMPOSE_LINK) == {}


